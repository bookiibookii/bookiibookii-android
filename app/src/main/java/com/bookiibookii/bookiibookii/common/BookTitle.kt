package com.bookiibookii.bookiibookii.common

/**
 * 책 제목에서 부제목을 제거한 표시용 제목을 반환한다.
 *
 * 알라딘 도서 제목은 `"본제목 - 부제목"` 형식(스페이스-하이픈-스페이스)으로 부제목을 붙인다.
 * 첫 `" - "` 앞부분만 남겨 본제목만 표시한다. 단어 내 하이픈("K-팝" 등)은 건드리지 않는다.
 *
 * 예) "마션 - 스페셜 에디션" → "마션"
 *     "데미안 (오리지널 초판본 표지디자인) - 최신 원전 완역본" → "데미안 (오리지널 초판본 표지디자인)"
 *     "프로젝트 헤일메리" → "프로젝트 헤일메리" (구분자 없으면 원본 유지)
 *
 * 표시 전용 — 검색/네비/매칭에 쓰는 원본 제목은 그대로 두고 UI 출력 시에만 적용한다.
 */
fun String?.stripBookSubtitle(): String =
    this?.substringBefore(" - ")?.trimEnd().orEmpty()
